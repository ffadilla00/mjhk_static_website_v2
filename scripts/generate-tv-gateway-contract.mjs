#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const candidates = [
  path.join(root, "scripts", "tv-device-simulator.mjs"),
  path.join(root, "worker-tv-mjhk", "src", "index.js"),
];

const existing = candidates.filter((file) => fs.existsSync(file));

if (existing.length === 0) {
  console.error("[FAIL] Gateway/simulator source tidak ditemukan.");
  process.exit(1);
}

const allText = existing
  .map((file) => fs.readFileSync(file, "utf8"))
  .join("\n");

const headerLiterals = new Set();

for (const match of allText.matchAll(
  /(?:headers?\.get|headers?\.set|["']headers["']\s*:)?[\s\S]{0,80}?["']([a-z0-9-]{3,64})["']/gi
)) {
  const value = match[1];
  if (/(device|token|authorization)/i.test(value)) {
    headerLiterals.add(value);
  }
}

for (const match of allText.matchAll(
  /["']?([xX]-[A-Za-z0-9-]*(?:device|token)[A-Za-z0-9-]*)["']?\s*:/g
)) {
  headerLiterals.add(match[1]);
}

const headers = [...headerLiterals];

const canonicalCodeHeader =
  /headers\.get\(["']x-mjhk-device-code["']\)/i.test(allText)
    ? "x-mjhk-device-code"
    : null;

const canonicalTokenHeader =
  /headers\.get\(["']authorization["']\)/i.test(allText)
    ? "authorization"
    : null;

const codeHeader = canonicalCodeHeader || choose(headers, [
  /x-mjhk-device-code/i,
  /device.*code/i,
  /code.*device/i,
]);

const tokenHeader = canonicalTokenHeader || choose(headers, [
  /^authorization$/i,
  /device.*token/i,
  /token.*device/i,
]);

if (!codeHeader || !tokenHeader) {
  console.log("=== DISCOVERED HEADER CANDIDATES ===");
  for (const header of headers) console.log("-", header);

  console.error(
    "\n[FAIL] Exact device auth headers belum bisa ditentukan otomatis.\n" +
    "Jalankan grep command dari README dan review source snippet."
  );
  process.exit(2);
}

const bearer =
  tokenHeader.toLowerCase() === "authorization" &&
  /Bearer\s+/i.test(allText);

const output = `/*
 * AUTO-GENERATED by scripts/generate-tv-gateway-contract.mjs
 * Do not put tokens/secrets in this file.
 */
export const DEVICE_AUTH_CONTRACT = Object.freeze({
  ready: true,
  deviceCodeHeader: ${JSON.stringify(codeHeader)},
  deviceTokenHeader: ${JSON.stringify(tokenHeader)},
  tokenScheme: ${JSON.stringify(bearer ? "bearer" : "raw")},
  source: "repo-source-audit",
});
`;

const outFile = path.join(
  root,
  "tv-player",
  "assets",
  "js",
  "gateway-contract.generated.js"
);

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, output, "utf8");

console.log("=== MJHK TV GATEWAY CONTRACT ===");
console.log("[PASS] Device code header:", codeHeader);
console.log("[PASS] Device token header:", tokenHeader);
console.log("[PASS] Token scheme:", bearer ? "bearer" : "raw");
console.log("[PASS] Written:", path.relative(root, outFile));
console.log("[SECURITY] No token/secret value printed.");

function choose(values, patterns) {
  for (const pattern of patterns) {
    const found = values.find((value) => pattern.test(value));
    if (found) return found;
  }
  return null;
}
