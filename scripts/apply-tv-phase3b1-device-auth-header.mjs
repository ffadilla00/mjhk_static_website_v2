#!/usr/bin/env node

import fs from "node:fs";

const workerFile = "worker-tv-mjhk/src/index.js";
const generatorFile = "scripts/generate-tv-gateway-contract.mjs";
const generatedFile = "tv-player/assets/js/gateway-contract.generated.js";

for (const file of [workerFile, generatorFile]) {
  if (!fs.existsSync(file)) {
    console.error(`[FAIL] ${file} tidak ditemukan`);
    process.exit(1);
  }
}

let worker = fs.readFileSync(workerFile, "utf8");
let generator = fs.readFileSync(generatorFile, "utf8");

if (!worker.includes('request.headers.get("x-mjhk-device-code")')) {
  console.error("[FAIL] Worker canonical x-mjhk-device-code contract tidak ditemukan");
  process.exit(2);
}

if (!worker.includes('authorization.startsWith("Bearer ")')) {
  console.error("[FAIL] Worker Bearer auth contract tidak ditemukan");
  process.exit(3);
}

// Fix CORS allow-header to match the actual Worker auth contract.
worker = worker.replace(
  'const CORS_ALLOW_HEADERS = "Content-Type, device-code, authorization";',
  'const CORS_ALLOW_HEADERS = "Content-Type, x-mjhk-device-code, authorization";'
);

// Make generator prefer the exact Worker readDeviceAuth literal.
// This prevents future false discovery from documentation/CORS strings.
if (!generator.includes("const canonicalCodeHeader")) {
  const marker = "const headers = [...headerLiterals];";
  if (!generator.includes(marker)) {
    console.error("[FAIL] Generator marker tidak ditemukan");
    process.exit(4);
  }

  generator = generator.replace(
    marker,
`${marker}

const canonicalCodeHeader =
  /headers\\.get\\(["']x-mjhk-device-code["']\\)/i.test(allText)
    ? "x-mjhk-device-code"
    : null;

const canonicalTokenHeader =
  /headers\\.get\\(["']authorization["']\\)/i.test(allText)
    ? "authorization"
    : null;`
  );

  generator = generator.replace(
`const codeHeader = choose(headers, [
  /device.*code/i,
  /code.*device/i,
]);`,
`const codeHeader = canonicalCodeHeader || choose(headers, [
  /x-mjhk-device-code/i,
  /device.*code/i,
  /code.*device/i,
]);`
  );

  generator = generator.replace(
`const tokenHeader = choose(headers, [
  /device.*token/i,
  /token.*device/i,
  /^authorization$/i,
]);`,
`const tokenHeader = canonicalTokenHeader || choose(headers, [
  /^authorization$/i,
  /device.*token/i,
  /token.*device/i,
]);`
  );
}

fs.writeFileSync(workerFile, worker, "utf8");
fs.writeFileSync(generatorFile, generator, "utf8");

// Write the exact known contract immediately.
// The generator is also fixed so a future regenerate stays correct.
const generated = `/*
 * AUTO-GENERATED by scripts/generate-tv-gateway-contract.mjs
 * Do not put tokens/secrets in this file.
 */
export const DEVICE_AUTH_CONTRACT = Object.freeze({
  ready: true,
  deviceCodeHeader: "x-mjhk-device-code",
  deviceTokenHeader: "authorization",
  tokenScheme: "bearer",
  source: "worker-readDeviceAuth-contract",
});
`;

fs.writeFileSync(generatedFile, generated, "utf8");

console.log("[PASS] Browser device header -> x-mjhk-device-code");
console.log("[PASS] Browser token scheme -> Bearer");
console.log("[PASS] Worker CORS allow-header -> x-mjhk-device-code");
console.log("[PASS] Contract generator canonical priority diperbaiki");
console.log("[SECURITY] Tidak ada device token value dibaca/ditampilkan");
console.log("RESULT: APPLIED");
